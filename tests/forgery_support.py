"""Support for constructing genuine (non-stubbed) forged Ed25519 signatures
that isolate a single §9 structural check, for tests/test_sign_forgery.py.

Every point/scalar operation here goes through libsodium's own C-backed
primitives (crypto_scalarmult_ed25519_base_noclamp, crypto_core_ed25519_add)
or is plain modular integer arithmetic on already-decoded scalars -- no
Ed25519 curve arithmetic is reimplemented, consistent with CLAUDE.md §9.

Background: libsodium's verification checks encode(s*B - h*A) == R exactly
(not up to cofactor). Whenever A has prime order L, s*B - h*A is confined to
<B> (both terms lie in the prime-order subgroup generated by B), so R is
*forced* to be prime-order too -- an "R invalid, A valid" accepted forgery
is mathematically impossible against this equation, not merely hard to
find (see test_sign_forgery.IsolatedRForgeryIsImpossibleTests). An
"A invalid, R valid" forgery IS constructible: choosing A = A0 + T where T
has order 2 makes s*B - h*A land back on R0 exactly whenever h is even,
which happens for about half of all messages/nonces.
"""

import ctypes
import hashlib

from trust_kernel import sign

IDENTITY = bytes([0x01] + [0x00] * 31)

# Small-order point published in "Taming the Many EdDSAs" (Chalkias,
# Garillot, Nikolaenko, SSR 2020), case 0's pub_key -- see
# tests/vectors/ed25519_speccheck_vectors.json. Has order exactly 8.
SMALL_ORDER_GENERATOR = bytes.fromhex(
    "c7176a703d4dd84fba3c0b760d10670f2a2053fa2c39ccc64ec7fd7792ac03fa"
)


def _lib():
    lib = sign._load()
    lib.crypto_scalarmult_ed25519_base_noclamp.argtypes = [
        ctypes.c_char_p, ctypes.c_char_p,
    ]
    lib.crypto_scalarmult_ed25519_base_noclamp.restype = ctypes.c_int
    lib.crypto_core_ed25519_add.argtypes = [
        ctypes.c_char_p, ctypes.c_char_p, ctypes.c_char_p,
    ]
    lib.crypto_core_ed25519_add.restype = ctypes.c_int
    lib.crypto_sign_verify_detached.argtypes = [
        ctypes.c_char_p, ctypes.c_char_p, ctypes.c_ulonglong, ctypes.c_char_p,
    ]
    lib.crypto_sign_verify_detached.restype = ctypes.c_int
    return lib


def scalarmult_base(scalar32: bytes) -> bytes:
    out = ctypes.create_string_buffer(32)
    assert _lib().crypto_scalarmult_ed25519_base_noclamp(out, scalar32) == 0
    return out.raw


def point_add(p: bytes, q: bytes) -> bytes:
    out = ctypes.create_string_buffer(32)
    assert _lib().crypto_core_ed25519_add(out, p, q) == 0
    return out.raw


def raw_libsodium_verify(pub_key: bytes, message: bytes, signature: bytes) -> bool:
    """Bypasses trust_kernel.sign.verify()'s §9 gates entirely -- calls
    libsodium's crypto_sign_verify_detached directly, to establish that a
    forged signature really is accepted by the underlying library and not
    only rejected or accepted by our own logic."""
    lib = _lib()
    return lib.crypto_sign_verify_detached(
        signature, message, ctypes.c_ulonglong(len(message)), pub_key
    ) == 0


def derive_scalar(seed: bytes) -> bytes:
    """RFC 8032 §5.1.5 secret-scalar derivation: hash + bit-clamping only,
    no curve arithmetic."""
    h = hashlib.sha512(seed).digest()
    a = bytearray(h[:32])
    a[0] &= 248
    a[31] &= 127
    a[31] |= 64
    return bytes(a)


def torsion_subgroup():
    """The 8-element small-order subgroup generated by SMALL_ORDER_GENERATOR
    (identity plus 7 nonzero small-order points), via repeated libsodium
    point addition."""
    points = [IDENTITY]
    cur = IDENTITY
    for _ in range(7):
        cur = point_add(cur, SMALL_ORDER_GENERATOR)
        points.append(cur)
    return points
