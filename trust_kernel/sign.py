"""Ed25519 sign/verify per CLAUDE.md §9 (FROZEN rule set).

Serves T4 (verdict authenticity + freshness): two honest verifiers running
this module against the same bytes must never disagree. That is why
verification is restricted to the domain where cofactored and cofactorless
verification produce identical results (canonical, prime-order-subgroup R;
canonical, prime-order-subgroup A; canonical S < L) rather than picking a
side of the ZIP-215/RFC-8032 disagreement. Outside that domain there is
nothing to disagree about, so the signature is rejected.

C-backed (libsodium) by requirement: Ed25519 point/scalar arithmetic is
never implemented in pure Python here. The one exception is the scalar
canonicality check (S < L), which is plain integer comparison of an
already-decoded byte string against a constant, not curve arithmetic.
"""

import ctypes
import ctypes.util
import threading

# Order of the prime-order subgroup (RFC 8032 §5.1: "L").
L = 2 ** 252 + 27742317777372353535851937790883648493

SEED_BYTES = 32
PUBLIC_KEY_BYTES = 32
SECRET_KEY_BYTES = 64
SIGNATURE_BYTES = 64

_init_lock = threading.Lock()
_sodium = None


class SigningError(Exception):
    """Raised on failures in trusted-input paths (keygen, signing, provisioning)."""


def _load():
    global _sodium
    if _sodium is not None:
        return _sodium
    with _init_lock:
        if _sodium is not None:
            return _sodium
        libname = ctypes.util.find_library("sodium")
        if libname is None:
            raise SigningError("libsodium not found on this system")
        lib = ctypes.CDLL(libname)
        if lib.sodium_init() < 0:
            raise SigningError("sodium_init() failed")

        lib.crypto_sign_keypair.argtypes = [ctypes.c_char_p, ctypes.c_char_p]
        lib.crypto_sign_keypair.restype = ctypes.c_int

        lib.crypto_sign_seed_keypair.argtypes = [
            ctypes.c_char_p, ctypes.c_char_p, ctypes.c_char_p,
        ]
        lib.crypto_sign_seed_keypair.restype = ctypes.c_int

        lib.crypto_sign_detached.argtypes = [
            ctypes.c_char_p,
            ctypes.POINTER(ctypes.c_ulonglong),
            ctypes.c_char_p,
            ctypes.c_ulonglong,
            ctypes.c_char_p,
        ]
        lib.crypto_sign_detached.restype = ctypes.c_int

        lib.crypto_sign_verify_detached.argtypes = [
            ctypes.c_char_p, ctypes.c_char_p, ctypes.c_ulonglong, ctypes.c_char_p,
        ]
        lib.crypto_sign_verify_detached.restype = ctypes.c_int

        lib.crypto_core_ed25519_is_valid_point.argtypes = [ctypes.c_char_p]
        lib.crypto_core_ed25519_is_valid_point.restype = ctypes.c_int

        _sodium = lib
        return lib


def generate_keypair():
    """Return (public_key, secret_key) freshly generated by libsodium's CSPRNG."""
    lib = _load()
    pk = ctypes.create_string_buffer(PUBLIC_KEY_BYTES)
    sk = ctypes.create_string_buffer(SECRET_KEY_BYTES)
    if lib.crypto_sign_keypair(pk, sk) != 0:
        raise SigningError("keypair generation failed")
    return pk.raw, sk.raw


def keypair_from_seed(seed: bytes):
    """Deterministic keypair derivation (RFC 8032-style seed expansion). Test use."""
    if len(seed) != SEED_BYTES:
        raise SigningError(f"seed must be {SEED_BYTES} bytes")
    lib = _load()
    pk = ctypes.create_string_buffer(PUBLIC_KEY_BYTES)
    sk = ctypes.create_string_buffer(SECRET_KEY_BYTES)
    if lib.crypto_sign_seed_keypair(pk, sk, seed) != 0:
        raise SigningError("keypair generation failed")
    return pk.raw, sk.raw


def sign(secret_key: bytes, message: bytes) -> bytes:
    """Detached Ed25519 signature over `message`."""
    if len(secret_key) != SECRET_KEY_BYTES:
        raise SigningError(f"secret key must be {SECRET_KEY_BYTES} bytes")
    lib = _load()
    sig = ctypes.create_string_buffer(SIGNATURE_BYTES)
    siglen = ctypes.c_ulonglong(0)
    rc = lib.crypto_sign_detached(
        sig, ctypes.byref(siglen), message, ctypes.c_ulonglong(len(message)), secret_key
    )
    if rc != 0:
        raise SigningError("signing failed")
    return sig.raw[: siglen.value]


def _is_valid_point(encoded: bytes) -> bool:
    """Canonical encoding, on-curve, prime-order subgroup, not small-order.

    This is the libsodium primitive that discharges both the "reject
    non-canonical R/A" and "R/A in the prime-order subgroup" rules of §9 in
    one call — it is precisely what restricts verification to the domain
    where cofactored and cofactorless agree.
    """
    lib = _load()
    return lib.crypto_core_ed25519_is_valid_point(encoded) == 1


def _scalar_is_canonical(s: bytes) -> bool:
    """True iff s, read little-endian, is < L (§9: reject S >= L / malleability)."""
    return int.from_bytes(s, "little") < L


def validate_public_key(public_key: bytes) -> bytes:
    """Provisioning-time gate (§9): canonical encoding, prime-order subgroup.

    Raises on failure — provisioning a bad key is a configuration error, not
    an adversarial input to be silently rejected.
    """
    if len(public_key) != PUBLIC_KEY_BYTES:
        raise SigningError(f"public key must be {PUBLIC_KEY_BYTES} bytes")
    if not _is_valid_point(public_key):
        raise SigningError("public key is not a canonical prime-order-subgroup point")
    return public_key


def verify(public_key: bytes, message: bytes, signature: bytes) -> bool:
    """§9 rule set. Returns False for any structural or cryptographic failure;
    never raises on adversarial input — verify() is a pure predicate over
    untrusted bytes, consistent with §10's fail-to-LOW discipline.
    """
    if len(public_key) != PUBLIC_KEY_BYTES or len(signature) != SIGNATURE_BYTES:
        return False

    r = signature[:32]
    s = signature[32:]

    if not _scalar_is_canonical(s):
        return False

    if not _is_valid_point(r):
        return False

    if not _is_valid_point(public_key):
        return False

    lib = _load()
    rc = lib.crypto_sign_verify_detached(
        signature, message, ctypes.c_ulonglong(len(message)), public_key
    )
    return rc == 0
