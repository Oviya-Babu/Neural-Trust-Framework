"""Device evidence producer (CLAUDE.md §2, §10, Phase 8 Step 3).

Per config/claim_registry.json's device.provisional_v0 entry:
measurement_source=EMULATED_PROTOCOL, host_independence=SAME_HOST,
forgeable_under_A_code=TRUE, and OFF-path: "the EEG data path does not
traverse this DTLS channel, only the emulated device-link protocol under
test does." This producer drives and verifies a genuine OpenSSL DTLS
handshake (real cryptography, real protocol state machine, via the
system `openssl s_server`/`s_client -dtls` binaries over UDP loopback,
certs generated by sensors/device_certs.py using the `cryptography`
library) -- but that handshake is a standalone protocol exercise, not a
transport the actual BCI signal traverses in this software-only prototype
(§1: no live BCI hardware). Reported as EMULATED_PROTOCOL and OFF-path for
that reason, not because the DTLS mechanics themselves are faked.

Runtime component: a per-session device-link check -- a DTLS handshake
against the device's certificate (verified against a pinned CA) plus an
application-level sequence/replay-counter check riding on top of the
DTLS-protected channel.

Runtime measurement, two parts:
  1. Handshake/certificate result: does a real DTLS handshake against this
     device's presented certificate succeed, with that certificate
     verifying against the pinned CA (run_dtls_handshake). This is a
     protocol-level check: an expired cert, a cert not signed by the
     pinned CA, or any TLS-record-level tamper all surface as a real
     OpenSSL handshake failure, not a hand-simulated boolean.
  2. Sequence/replay check (SequenceReplayGuard): a sliding-window
     anti-replay check, structurally the same idea as DTLS's own record-
     sequence anti-replay window (RFC 6347 §4.1.2.6) -- implemented at the
     application layer here because the OpenSSL CLI used for (1) does not
     expose DTLS's internal replay window for inspection. This producer
     checks its own sequence counter riding on top of the separately-
     verified DTLS link, and is documented as such rather than claimed to
     be reading OpenSSL's internal anti-replay state.

Mathematical calculation: raw_measurement = DEVICE_TRUST_CEIL if
(handshake_ok AND sequence_accepted) else DEVICE_TRUST_FLOOR -- a two-
factor AND, for the same reason as Model's integrity check (sensors/
model_sensor.py): a valid handshake riding a replayed sequence number is
not trustworthy, and vice versa.

measurement units: dimensionless trust extreme, fixed-point int in
{DEVICE_TRUST_FLOOR, DEVICE_TRUST_CEIL}.
claim type: device.provisional_v0. trust dimension: Device.
timestamp/provenance: caller-supplied window_id/claimed_at.
expected polarity: +1 (higher raw = more trustworthy, per config/eis.v0.json).
window binding: the handshake is a per-session check (re-announced per
window like Model's, CLAUDE.md §10's "exactly one statement per registered
claim type per window"); the sequence/replay check is genuinely per-window,
since each window's device-link message must carry its own sequence
number.
smoothing: none.
attacks influencing this measurement: invalid cert (an attacker's own
cert substituted at the device link, not signed by the pinned CA) --
caught at DTLS chain verification. Expired cert -- caught at DTLS
certificate-validity verification. Replayed sequence -- caught by
SequenceReplayGuard. Device is a LENIENT dimension (§4): "failure
degrades confidence; bounded actuation is proportionate and halting is
itself a hazard for a mobility actuator" -- this producer measures the
same honest-evidence-conditional integrity signal as the strict-dimension
producers, the leniency is policy's decision (config/crit_table.json), not
something this producer implements itself.

No confidence is computed here (§2): this is a raw measurement only.
"""

import socket
import subprocess
import tempfile

from trust_kernel import schema

DEVICE_CLAIM_TYPE = "device.provisional_v0"
DEVICE_SOURCE_ID = "device_sensor_v0"
DEVICE_BOUNDARY = "TB2"

DEVICE_TRUST_FLOOR = -100
DEVICE_TRUST_CEIL = 100

REPLAY_WINDOW_SIZE = 64

HANDSHAKE_SERVER_STARTUP_S = 0.4
HANDSHAKE_TIMEOUT_S = 4.0


def _free_udp_port() -> int:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


def run_dtls_handshake(server_combined_pem: bytes, ca_cert_pem: bytes,
                        timeout_s: float = HANDSHAKE_TIMEOUT_S) -> dict:
    """Drives a real `openssl s_server -dtls` <-> `openssl s_client -dtls`
    handshake over UDP loopback. server_combined_pem holds the server's
    cert+key concatenated (as sensors/device_certs.py produces); ca_cert_pem
    is the CA the client verifies the server cert against.

    Returns {"handshake_ok": bool, "client_exit_code": int,
    "client_output": str} -- handshake_ok is exactly "the client process
    exited 0", the real signal for a successful, chain-verified DTLS
    handshake under -verify_return_error (a verify failure or protocol
    failure makes the client exit non-zero)."""
    port = _free_udp_port()
    server_proc = None
    with tempfile.NamedTemporaryFile(suffix=".pem") as server_file, \
            tempfile.NamedTemporaryFile(suffix=".pem") as ca_file:
        server_file.write(server_combined_pem)
        server_file.flush()
        ca_file.write(ca_cert_pem)
        ca_file.flush()

        try:
            server_proc = subprocess.Popen(
                ["openssl", "s_server", "-dtls", "-quiet", "-naccept", "1",
                 "-accept", f"127.0.0.1:{port}", "-cert", server_file.name, "-key", server_file.name],
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            )
            import time
            time.sleep(HANDSHAKE_SERVER_STARTUP_S)

            client_proc = subprocess.run(
                ["openssl", "s_client", "-dtls", "-connect", f"127.0.0.1:{port}",
                 "-CAfile", ca_file.name, "-verify_return_error"],
                stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                timeout=timeout_s,
            )
            client_output = client_proc.stdout.decode(errors="replace")
            return {
                "handshake_ok": client_proc.returncode == 0,
                "client_exit_code": client_proc.returncode,
                "client_output": client_output,
            }
        except subprocess.TimeoutExpired:
            return {"handshake_ok": False, "client_exit_code": None, "client_output": "client timed out"}
        finally:
            if server_proc is not None:
                server_proc.terminate()
                try:
                    server_proc.wait(timeout=2.0)
                except subprocess.TimeoutExpired:
                    server_proc.kill()
                    server_proc.wait()
                if server_proc.stdout is not None:
                    server_proc.stdout.close()


class SequenceReplayGuard:
    """Sliding-window anti-replay check (see module docstring). Stateful
    per device-link identity -- the sensor contract explicitly permits
    sensor-side state (CLAUDE.md §11 layout: 'sensors/ (6 pluggable,
    sensor-side state permitted)'; §10: 'Sensors may hold state; sensors
    are not pure.')."""

    def __init__(self, window_size: int = REPLAY_WINDOW_SIZE):
        self.window_size = window_size
        self._highest_seen = -1
        self._window_bitmap = 0

    def check_and_record(self, sequence_number: int) -> bool:
        """Returns True iff sequence_number is accepted (not a replay and
        not outside the window). Always updates state -- §10's fixed-order
        admission discipline: a rejected sequence number is still recorded,
        so re-presenting it is caught every time, not just the first."""
        if sequence_number > self._highest_seen:
            shift = sequence_number - self._highest_seen
            if shift >= self.window_size:
                self._window_bitmap = 0
            else:
                self._window_bitmap = (self._window_bitmap << shift) & ((1 << self.window_size) - 1)
            self._highest_seen = sequence_number
            self._window_bitmap |= 1
            return True
        offset = self._highest_seen - sequence_number
        if offset >= self.window_size:
            return False
        bit = 1 << offset
        if self._window_bitmap & bit:
            return False
        self._window_bitmap |= bit
        return True


def measure_device_link(handshake_result: dict, sequence_accepted: bool) -> int:
    ok = bool(handshake_result.get("handshake_ok")) and sequence_accepted
    return DEVICE_TRUST_CEIL if ok else DEVICE_TRUST_FLOOR


class DeviceSensor:
    def __init__(self, secret_key: bytes, key_id: str = DEVICE_SOURCE_ID, source_id: str = DEVICE_SOURCE_ID):
        self._secret_key = secret_key
        self.key_id = key_id
        self.source_id = source_id
        self.replay_guard = SequenceReplayGuard()

    def build_statement(self, *, handshake_result: dict, sequence_number: int,
                         window_id: int, claimed_at: int) -> dict:
        sequence_accepted = self.replay_guard.check_and_record(sequence_number)
        raw = measure_device_link(handshake_result, sequence_accepted)
        fields = schema.build_statement(
            key_id=self.key_id, source_id=self.source_id, boundary=DEVICE_BOUNDARY,
            claim_type=DEVICE_CLAIM_TYPE, raw_measurement=raw,
            window_id=window_id, claimed_at=claimed_at,
        )
        return schema.sign_statement(self._secret_key, fields)
